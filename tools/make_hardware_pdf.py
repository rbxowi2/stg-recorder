def head(c, title, sub=""):
    c.setFillColor(INK)
    c.setFont(FB, 17)
    c.drawString(45, H - 55, title)
    if sub:
        c.setFillColor(MUTE)
        c.setFont(F, 9.5)
        c.drawString(45, H - 72, sub)
    c.setStrokeColor(HexColor("#e2e8f0"))
    c.setLineWidth(1)
    c.line(45, H - 82, W - 45, H - 82)


def foot(c, n):
    c.setFillColor(MUTE)
    c.setFont(F, 8)
    c.drawString(45, 30, "stg-recorder hardware  -  generated by tools/make_hardware_pdf.py")
    c.drawRightString(W - 45, 30, f"{n} / {N_PAGES}")


def table(c, x, y, w, rows, widths, title=None, color=INK):
    """Draw a simple table; returns the y below it."""
    if title:
        c.setFont(FB, 11.5)
        c.setFillColor(color)
        c.drawString(x, y, title)
        y -= 17
    rh = 17.0
    for i, row in enumerate(rows):
        if i == 0:
            c.setFillColor(HexColor("#f1f5f9"))
            c.rect(x, y - 4, w, rh, stroke=0, fill=1)
        cx = x
        for j, cell in enumerate(row):
            c.setFont(FB if i == 0 else F, 8.6)
            c.setFillColor(INK if i == 0 else BODY)
            c.drawString(cx + 5, y + 1, str(cell))
            cx += widths[j]
        y -= rh
        c.setStrokeColor(HexColor("#e2e8f0"))
        c.setLineWidth(0.6)
        c.line(x, y + rh - 4, x + w, y + rh - 4)
    return y - 8


def para(c, x, y, w, text, size=8.8, bold=False, color=None):
    """Word-wrapped paragraph; returns the y below it."""
    font = FB if bold else F
    c.setFont(font, size)
    c.setFillColor(color or BODY)
    line = ""
    for word in text.split():
        trial = (line + " " + word).strip()
        if pdfmetrics.stringWidth(trial, font, size) > w and line:
            c.drawString(x, y, line)
            y -= size * 1.45
            line = word
        else:
            line = trial
    if line:
        c.drawString(x, y, line)
        y -= size * 1.45
    return y


