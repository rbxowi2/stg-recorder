def page_header(c):
    head(c, "Pi 5 40-pin header",
         "Pin 1 is on the side nearest the board edge. Only coloured pins are wired.")

    x_l, x_r = 268.0, 327.0        # x of the two pin columns
    y0, dy = H - 118, 29.0
    r = 8.0

    c.setFillColor(HexColor("#f1f5f9"))
    c.setStrokeColor(HexColor("#cbd5e1"))
    c.roundRect(x_l - 20, y0 - 19 * dy - 18, (x_r - x_l) + 40,
                19 * dy + 36, 8, stroke=1, fill=1)

    for row in range(20):
        y = y0 - row * dy
        for side, pin in ((0, row * 2 + 1), (1, row * 2 + 2)):
            name, grp, note = PINS[pin]
            x = x_l if side == 0 else x_r
            col = C[grp]
            used = grp != "-"

            c.setFillColor(col)
            c.setStrokeColor(HexColor("#64748b") if used else HexColor("#cbd5e1"))
            c.setLineWidth(1.2 if used else 0.6)
            if used:
                c.circle(x, y, r, stroke=1, fill=1)
            else:
                c.setFillColor(white)
                c.circle(x, y, r - 2, stroke=1, fill=1)

            c.setFont(FB if used else F, 7)
            c.setFillColor(white if used else MUTE)
            c.drawCentredString(x, y - 2.4, str(pin))

            c.setFont(FB if used else F, 8.6)
            c.setFillColor(INK if used else MUTE)
            if side == 0:
                c.drawRightString(x - 14, y - 3, name)
                if note:
                    c.setFillColor(col)
                    c.setFont(F, 8.4)
                    c.drawRightString(x - 14 - pdfmetrics.stringWidth(
                        name, FB, 8.6) - 8, y - 3, note)
            else:
                c.drawString(x + 14, y - 3, name)
                if note:
                    c.setFillColor(col)
                    c.setFont(F, 8.4)
                    c.drawString(x + 14 + pdfmetrics.stringWidth(
                        name, FB, 8.6) + 8, y - 3, note)

    y = 88
    c.setFont(FB, 9)
    c.setFillColor(INK)
    c.drawString(45, y + 16, "Legend")
    items = [("OLED", "OLED (I2C1), 4 wires"), ("BTN", "buttons, 3 wires"),
             ("I2S", "microphones (I2S)"), ("PWR", "3.3 V supply"),
             ("BLOCK", "reserved, not wired"), ("-", "free")]
    x = 45
    for grp, label in items:
        c.setFillColor(C[grp])
        c.setStrokeColor(HexColor("#64748b"))
        c.setLineWidth(0.8)
        c.circle(x + 5, y, 5.5, stroke=1, fill=1)
        c.setFillColor(INK)
        c.setFont(F, 8.4)
        c.drawString(x + 15, y - 3, label)
        x += 15 + pdfmetrics.stringWidth(label, F, 8.4) + 18

    foot(c, 2)
    c.showPage()


