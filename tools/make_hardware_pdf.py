def page_layout(c):
    head(c, "Rig layout",
         "Rear view: standing behind the rig, looking where the cameras look.")

    cx, cy = W / 2, H - 250
    bw, bh = 230, 132
    sx_off, sy_off = 70, 36
    c.setStrokeColor(HexColor("#475569"))
    c.setLineWidth(1.6)
    c.setFillColor(HexColor("#f8fafc"))
    c.roundRect(cx - bw / 2, cy - bh / 2, bw, bh, 8, stroke=1, fill=1)

    cams = [("cam_C", -1, 1), ("cam_B", 1, 1), ("cam_D", -1, -1), ("cam_A", 1, -1)]
    for name, sx, sy in cams:
        x = cx + sx * sx_off
        y = cy + sy * sy_off
        c.setFillColor(HexColor("#334155"))
        c.circle(x, y, 16, stroke=0, fill=1)
        c.setFillColor(white)
        c.setFont(FB, 7.4)
        c.drawCentredString(x, y - 2.6, name)

    c.setFillColor(MUTE)
    c.setFont(F, 8.6)
    c.drawCentredString(cx, cy + bh / 2 + 10, "seen from behind (cameras point away from you)")

    c.setStrokeColor(C["PWR"])
    c.setLineWidth(0.9)
    c.line(cx - sx_off, cy - bh / 2 - 14, cx + sx_off, cy - bh / 2 - 14)
    c.setFillColor(C["PWR"])
    c.setFont(F, 8.2)
    c.drawCentredString(cx, cy - bh / 2 - 25, f"{EDGE_H:.1f} mm")

    c.line(cx - bw / 2 - 10, cy - sy_off, cx - bw / 2 - 10, cy + sy_off)
    c.saveState()
    c.translate(cx - bw / 2 - 15, cy)
    c.rotate(90)
    c.drawCentredString(0, 0, f"{EDGE_V:.1f} mm")
    c.restoreState()

    c.setDash(3, 2)
    c.line(cx - sx_off, cy + sy_off, cx + sx_off, cy - sy_off)
    c.setDash()
    c.drawString(cx + 6, cy + 6, f"{EDGE_D:.1f} mm")

    for sx, lab in ((-1, "mic L  SEL->GND"), (1, "mic R  SEL->3.3V")):
        x = cx + sx * (bw / 2 + 62)
        c.setFillColor(C["I2S"])
        c.circle(x, cy, 9, stroke=0, fill=1)
        c.setFillColor(INK)
        c.setFont(F, 8.2)
        c.drawCentredString(x, cy - 24, lab)
    c.setStrokeColor(C["I2S"])
    c.line(cx - bw / 2 - 62, cy + bh / 2 + 26, cx + bw / 2 + 62, cy + bh / 2 + 26)
    c.setFillColor(C["I2S"])
    c.drawCentredString(cx, cy + bh / 2 + 30, f"microphones {MIC_MM:.0f} mm apart")

    y = cy - bh / 2 - 50
    y = table(c, 45, y, W - 90,
              [["Camera pair", "Distance between centers (mm)"],
               ["cam_C - cam_B,  cam_D - cam_A (horizontal)", f"{EDGE_H:.1f}"],
               ["cam_C - cam_D,  cam_B - cam_A (vertical)", f"{EDGE_V:.1f}"],
               ["cam_A - cam_C,  cam_B - cam_D (diagonal)", f"{EDGE_D:.1f}"]],
              [(W - 90) * .62, (W - 90) * .38],
              "Measured camera spacing")
    y = para(c, 45, y - 2, W - 90,
             "Measure between lens centers, not housing edges. These six distances are passed "
             "to calibration (--edge) to give the reconstruction its metric scale; measure again "
             "whenever the rig is rebuilt.")

    y -= 8
    y = table(c, 45, y, W - 90,
              [["Placement", "Reason"],
               ["Cameras in a rigid 2x2 grid, axes nearly parallel", "the rig is the window frame; measured axes differ by 1.1-1.6 deg"],
               ["Camera names follow USB ports", "keep each camera on its port; moving one requires a new calibration"],
               ["Microphones at the outer left and right edges", "wider spacing gives a clearer stereo image"],
               ["OLED and buttons on the back, via jumper wires", "a HAT on the header would collide with the camera mount"],
               ["Left / right as the cameras see", "matches the calibration: cam_A is at +x (right), cam_C at -x, -y"]],
              [(W - 90) * .45, (W - 90) * .55],
              "Placement")

    y = para(c, 45, y - 2, W - 90, "Checks after wiring", size=11.5, bold=True, color=INK)
    y = table(c, 45, y - 4, W - 90,
              [["What", "Command / action", "Expected"],
               ["OLED detected", "i2cdetect -y 1", "3c (or 3d) appears"],
               ["Buttons", "gpioget gpiochip0 5 6", "1 released, 0 pressed"],
               ["Microphone device", "arecord -l", "the I2S card is listed"],
               ["Sound captured", "rig.py menu: mic test", "both bars move"],
               ["Left / right", "mic test, tap the left microphone", "only the L bar jumps"]],
              [(W - 90) * .24, (W - 90) * .46, (W - 90) * .30])
    para(c, 45, y - 4, W - 90,
         "All checks must pass. If one fails, check that group's wires only; the three "
         "groups are independent.")

    foot(c, 4)
    c.showPage()


def main():
    c = canvas.Canvas(OUT, pagesize=A4)
    c.setTitle("stg-recorder hardware")
    page_parts(c)
    page_header(c)
    page_wiring(c)
    page_layout(c)
    c.save()
    print("->", OUT, f"{os.path.getsize(OUT)/1024:.0f} KB")


if __name__ == "__main__":
    main()
